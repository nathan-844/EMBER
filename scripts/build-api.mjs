// Bundles the Vercel Functions into self-contained ESM files:
//   api/ai-status.mjs  (GET)     api/analyze.mjs  (POST)
// Everything (NASA data, run tables, recorded answers, @vercel/functions) is inlined, so the
// deployed functions resolve nothing at runtime. Usage: npm run build:api  (also part of npm run build)
// `--check` exits 1 if the committed bundles are out of date.
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

const entries = {
  "ai-status": 'export { handle as GET } from "../server/vercel";',
  analyze: 'export { handle as POST } from "../server/vercel";',
};
const check = process.argv.includes("--check");
mkdirSync("api", { recursive: true });
let stale = 0;

for (const [name, contents] of Object.entries(entries)) {
  const result = await build({
    stdin: { contents, resolveDir: "api", sourcefile: `${name}.entry.ts`, loader: "ts" },
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    minify: false,
    legalComments: "none",
    write: false,
    logLevel: "warning",
    // Some CommonJS dependencies call require(); give the ESM bundle one.
    banner: { js: "// Generated by scripts/build-api.mjs from server/. Do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  });
  const code = result.outputFiles[0].text;
  const file = `api/${name}.mjs`;
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== code) {
      console.log(`${file} is out of date: run npm run build:api`);
      stale++;
    }
  } else {
    writeFileSync(file, code);
    console.log(`${file}: ${(code.length / 1024).toFixed(0)} KB`);
  }
}
if (stale) process.exit(1);
